export function getSupportTopic(topicId: string) {
  if (topicId === "payment") {
    return supportTopics.find((topic) => topic.id === "other") ?? supportTopics[0];
  }

  return supportTopics.find((topic) => topic.id === topicId) ?? supportTopics[0];
}
